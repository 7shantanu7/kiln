// testInputs are the x values every generated test checks.
var testInputs = []uint64{1, 42, 1 << 33}

// Write emits the repo under dir. dir must not exist or be empty.
func (r *Repo) Write(dir string) error {
	w := &writer{root: dir}
	w.file("CMakeLists.txt", r.rootCMake())
	w.file(".gitignore", "/build*/\n")
	w.file("fixture_config.h.in", r.configHeaderIn())
	w.file("tools/codegen.py", codegenPy(r.Cfg.Has("codegen-order")))
	for name, es := range r.Shared {
		w.file("libs/shared/"+name, defFile(es, ""))
	}
	for _, l := range r.Libs {
		r.writeLib(w, l)
	}
	man, _ := json.MarshalIndent(r.manifest(), "", "  ")
	w.file("kiln-fixture.json", string(man)+"\n")
	return w.err
}

type writer struct {
	root string
	err  error
}

func (w *writer) file(rel, content string) {
	if w.err != nil {
		return
	}
	p := filepath.Join(w.root, rel)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		w.err = err
		return
	}
	w.err = os.WriteFile(p, []byte(content), 0o644)
}

// Manifest describes a generated fixture; kiln-fixture.json holds it.
type Manifest struct {
	Config      Config      `json:"config"`
	Targets     int         `json:"targets"`
	TUs         int         `json:"translation_units"`
	Injected    []Injection `json:"injected_missing_deps"`
	NondetKinds []string    `json:"injected_nondeterminism"`
}

func (r *Repo) manifest() Manifest {
	var kinds []string
	for k, on := range r.Cfg.Nondet {
		if on {
			kinds = append(kinds, k)
		}
	}
	sort.Strings(kinds)
	return Manifest{
		Config:      r.Cfg,
		Targets:     2 * len(r.Libs),
		TUs:         len(r.Libs) * (r.Cfg.Modules + 1),
		Injected:    r.Injected,
		NondetKinds: kinds,
	}
}

func (r *Repo) rootCMake() string {
	var b strings.Builder
	b.WriteString(`# Generated by kiln-gen. Synthetic C++ monorepo used to exercise the kiln tools.
cmake_minimum_required(VERSION 3.20)
project(kiln_fixture LANGUAGES CXX)

set(CMAKE_CXX_STANDARD 17)
set(CMAKE_CXX_STANDARD_REQUIRED ON)
enable_testing()

find_package(Python3 REQUIRED COMPONENTS Interpreter)
set(KILN_FIXTURE_CODEGEN ${CMAKE_CURRENT_SOURCE_DIR}/tools/codegen.py)

`)
	if r.Cfg.Has("configure-timestamp") {
		b.WriteString("string(TIMESTAMP KILN_FIXTURE_STAMP \"%Y-%m-%dT%H:%M:%SZ\" UTC)\n")
	}
	b.WriteString("configure_file(fixture_config.h.in ${CMAKE_BINARY_DIR}/fixture_include/fixture_config.h @ONLY)\n\n")
	for _, l := range r.Libs {
		fmt.Fprintf(&b, "add_subdirectory(libs/%s)\n", l.Name)
	}
	return b.String()
}

func (r *Repo) configHeaderIn() string {
	var b strings.Builder
	b.WriteString("#pragma once\n")
	if r.Cfg.Has("configure-timestamp") {
		b.WriteString("#define KILN_FIXTURE_STAMP \"@KILN_FIXTURE_STAMP@\"\n")
	} else {
		b.WriteString("#define KILN_FIXTURE_STAMP \"fixture\"\n")
	}
	if r.Cfg.Has("configured-abspath") {
		b.WriteString("#define KILN_FIXTURE_DATA_DIR \"@CMAKE_BINARY_DIR@/data\"\n")
	} else {
		b.WriteString("#define KILN_FIXTURE_DATA_DIR \"data\"\n")
	}
	return b.String()
}

func codegenPy(unordered bool) string {
	order := "entries = sorted(entries.items())"
	if unordered {
		// Iterating a set of strings follows Python's per-process hash
		// randomization, so the table order changes from run to run.
		order = "entries = [(n, entries[n]) for n in set(entries)]"
	}
	return `#!/usr/bin/env python3
"""Fixture codegen: turns a .def file into a C++ header of constants.

Usage: codegen.py <prefix> <in.def> <out.h>
A .def file has lines "entry NAME VALUE" and "include RELATIVE_PATH".
"""
import os
import sys


def load(path, entries):
    with open(path) as f:
        for line in f:
            parts = line.split()
            if not parts:
                continue
            if parts[0] == "entry":
                entries[parts[1]] = int(parts[2])
            elif parts[0] == "include":
                load(os.path.join(os.path.dirname(path), parts[1]), entries)
            else:
                sys.exit("codegen: bad line in %s: %r" % (path, line))


def main():
    prefix, src, out = sys.argv[1:4]
    entries = {}
    load(src, entries)
    ` + order + `
    total = sum(v for _, v in entries) % (1 << 64)
    rows = "\n".join('    {"%s", %dULL},' % (n, v) for n, v in entries)
    text = (
        "// Generated by tools/codegen.py from %s. Do not edit.\n"
        "#pragma once\n"
        "namespace %s_gen {\n"
        "struct Entry { const char* name; unsigned long long value; };\n"
        "inline constexpr Entry kTable[] = {\n%s\n};\n"
        "inline constexpr unsigned long long kSum = %dULL;\n"
        "}  // namespace %s_gen\n" % (os.path.basename(src), prefix, rows, total, prefix)
    )
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as f:
        f.write(text)


if __name__ == "__main__":
    main()
`
}

func defFile(es []Entry, include string) string {
	var b strings.Builder
	for _, e := range es {
		fmt.Fprintf(&b, "entry %s %d\n", e.Name, e.Value)
	}
	if include != "" {
		fmt.Fprintf(&b, "include %s\n", include)
	}
	return b.String()
}

func (r *Repo) writeLib(w *writer, l *Lib) {
	base := "libs/" + l.Name
	mods := r.Cfg.Modules

	// CMake
	var c strings.Builder
	fmt.Fprintf(&c, "add_library(%s STATIC\n", l.Name)
	for m := 0; m < mods; m++ {
		fmt.Fprintf(&c, "  src/m%02d.cpp\n", m)
	}
	c.WriteString(")\n")
	fmt.Fprintf(&c, "target_include_directories(%s PUBLIC ${CMAKE_CURRENT_SOURCE_DIR}/include)\n", l.Name)
	if len(l.Deps) > 0 {
		fmt.Fprintf(&c, "target_link_libraries(%s PUBLIC", l.Name)
		for _, d := range l.Deps {
			fmt.Fprintf(&c, " %s", r.Libs[d].Name)
		}
		c.WriteString(")\n")
	}
	if l.Index == 0 {
		fmt.Fprintf(&c, "target_include_directories(%s PRIVATE ${CMAKE_BINARY_DIR}/fixture_include)\n", l.Name)
	}
	if l.Codegen != nil {
		fmt.Fprintf(&c, `set(_gen ${CMAKE_CURRENT_BINARY_DIR}/gen/%[1]s/gen.h)
add_custom_command(
  OUTPUT ${_gen}
  COMMAND ${Python3_EXECUTABLE} -B ${KILN_FIXTURE_CODEGEN} %[1]s ${CMAKE_CURRENT_SOURCE_DIR}/defs/%[1]s.def ${_gen}
  DEPENDS ${KILN_FIXTURE_CODEGEN} ${CMAKE_CURRENT_SOURCE_DIR}/defs/%[1]s.def
  COMMENT "codegen %[1]s")
target_sources(%[1]s PRIVATE ${_gen})
target_include_directories(%[1]s PUBLIC ${CMAKE_CURRENT_BINARY_DIR}/gen)
`, l.Name)
		inc := ""
		if l.Codegen.SharedInclude != "" {
			inc = "../../shared/" + l.Codegen.SharedInclude
		}
		w.file(base+"/defs/"+l.Name+".def", defFile(l.Codegen.Entries, inc))
	}
	for _, g := range l.RacyGen {
		// Injected bug: reaches into another target's generated directory
		// without a dependency on it.
		fmt.Fprintf(&c, "target_include_directories(%s PRIVATE ${CMAKE_BINARY_DIR}/libs/%s/gen)\n", l.Name, r.Libs[g].Name)
	}
	fmt.Fprintf(&c, `add_executable(%[1]s_test test/%[1]s_test.cpp)
target_link_libraries(%[1]s_test PRIVATE %[1]s)
add_test(NAME %[1]s_test COMMAND %[1]s_test)
`, l.Name)
	w.file(base+"/CMakeLists.txt", c.String())

	// Headers
	var u strings.Builder
	u.WriteString("#pragma once\n#include <cstdint>\n")
	for m := 0; m < mods; m++ {
		fmt.Fprintf(&u, "#include \"%s/m%02d.h\"\n", l.Name, m)
	}
	fmt.Fprintf(&u, "std::uint64_t %s_seed();\n", l.Name)
	w.file(fmt.Sprintf("%s/include/%s/%s.h", base, l.Name, l.Name), u.String())
	for m := 0; m < mods; m++ {
		w.file(fmt.Sprintf("%s/include/%s/m%02d.h", base, l.Name, m),
			fmt.Sprintf("#pragma once\n#include <cstdint>\nstd::uint64_t %s_m%02d(std::uint64_t x);\n", l.Name, m))
	}

	// Sources
	for m := 0; m < mods; m++ {
		w.file(fmt.Sprintf("%s/src/m%02d.cpp", base, m), r.moduleSource(l, m))
	}
	w.file(fmt.Sprintf("%s/test/%s_test.cpp", base, l.Name), r.testSource(l))
}

func (r *Repo) moduleSource(l *Lib, m int) string {
	k1, k2 := l.moduleConsts(m)
	fileCheck := m == 1 && l.Index%5 == 1
	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by kiln-gen.\n#include \"%s/m%02d.h\"\n", l.Name, m)
	for _, d := range l.Deps {
		fmt.Fprintf(&b, "#include \"%s/%s.h\"\n", r.Libs[d].Name, r.Libs[d].Name)
	}
	if m == 0 && l.Codegen != nil {
		fmt.Fprintf(&b, "#include \"%s/gen.h\"\n", l.Name)
	}
	if m == 1 {
		for _, g := range l.RacyGen {
			fmt.Fprintf(&b, "#include \"%s/gen.h\"\n", r.Libs[g].Name)
		}
	}
	if m == 0 && l.Index == 0 {
		b.WriteString("#include \"fixture_config.h\"\n")
	}
	b.WriteString("#include <algorithm>\n#include <array>\n#include <cstddef>\n#include <cstdint>\n#include <map>\n#include <string>\n")
	if fileCheck {
		b.WriteString("#include <cstdio>\n#include <cstdlib>\n")
		where := "__FILE__"
		if !r.Cfg.Has("file-macro") {
			where = fmt.Sprintf("%q", fmt.Sprintf("%s/src/m%02d.cpp", l.Name, m))
		}
		fmt.Fprintf(&b, "#define FIXTURE_CHECK(c) do { if (!(c)) { std::fprintf(stderr, \"%%s:%%d: check failed: %%s\\n\", %s, __LINE__, #c); std::abort(); } } while (0)\n", where)
	}
	fmt.Fprintf(&b, `
namespace {
constexpr std::uint64_t kMul = 0x%016XULL;
constexpr std::uint64_t kAdd = 0x%016XULL;
}  // namespace

std::uint64_t %s_m%02d(std::uint64_t x) {
  std::array<std::uint64_t, 8> a{};
  for (std::size_t k = 0; k < a.size(); ++k) a[k] = (x + k * 0x9E3779B97F4A7C15ULL) * kMul;
  std::sort(a.begin(), a.end());
`, k1, k2, l.Name, m)
	if fileCheck {
		b.WriteString("  FIXTURE_CHECK(std::is_sorted(a.begin(), a.end()));\n")
	}
	b.WriteString(`  std::map<std::string, std::uint64_t> tally;
  for (std::uint64_t v : a) tally["k" + std::to_string(v % 5)] += v >> 3;
  std::uint64_t v = kAdd;
  for (const auto& [key, val] : tally) v = (v ^ val) * 0x100000001B3ULL + key.size();
`)
	for _, d := range l.Deps {
		fmt.Fprintf(&b, "  v ^= %s_seed();\n", r.Libs[d].Name)
	}
	if m == 0 && l.Codegen != nil {
		fmt.Fprintf(&b, "  v += %s_gen::kSum;\n", l.Name)
	}
	if m == 1 {
		for _, g := range l.RacyGen {
			fmt.Fprintf(&b, "  v += %s_gen::kSum;\n", r.Libs[g].Name)
		}
	}
	b.WriteString("  return v;\n}\n")
	if m == 0 {
		fmt.Fprintf(&b, "\nstd::uint64_t %s_seed() { return 0x%016XULL; }\n", l.Name, l.Seed)
		if l.Codegen != nil {
			fmt.Fprintf(&b, "const char* %[1]s_gen_first() { return %[1]s_gen::kTable[0].name; }\n", l.Name)
		}
		if r.Cfg.Has("date-time") && l.Index%20 == 0 {
			fmt.Fprintf(&b, "const char* %[1]s_build_info() { return \"%[1]s built \" __DATE__ \" \" __TIME__; }\n", l.Name)
		}
		if l.Index == 0 {
			b.WriteString("const char* lib_0000_stamp() { return KILN_FIXTURE_STAMP; }\n")
			b.WriteString("const char* lib_0000_data_dir() { return KILN_FIXTURE_DATA_DIR; }\n")
		}
	}
	return b.String()
}

func (r *Repo) testSource(l *Lib) string {
	var b strings.Builder
	fmt.Fprintf(&b, `// Generated by kiln-gen. Expected values are computed by kiln-gen's Go model.
#include "%[1]s/%[1]s.h"
#include <cstdint>
#include <cstdio>

namespace {
struct Case {
  std::uint64_t (*fn)(std::uint64_t);
  std::uint64_t x;
  std::uint64_t want;
  const char* name;
};
const Case kCases[] = {
`, l.Name)
	for m := 0; m < r.Cfg.Modules; m++ {
		for _, x := range testInputs {
			fmt.Fprintf(&b, "    {%[1]s_m%02[2]d, %[3]dULL, 0x%016[4]XULL, \"%[1]s_m%02[2]d(%[3]d)\"},\n", l.Name, m, x, r.Eval(l, m, x))
		}
	}
	fmt.Fprintf(&b, `};
}  // namespace

int main() {
  int failures = 0;
  for (int rep = 0; rep < %d; ++rep) {
    for (const Case& c : kCases) {
      const std::uint64_t got = c.fn(c.x);
      if (got != c.want) {
        if (rep == 0) std::fprintf(stderr, "FAIL %%s: got 0x%%016llx want 0x%%016llx\n", c.name,
                                   static_cast<unsigned long long>(got), static_cast<unsigned long long>(c.want));
        ++failures;
      }
    }
  }
  if (%s_seed() != 0x%016XULL) ++failures;
  return failures == 0 ? 0 : 1;
}
`, r.Cfg.TestReps, l.Name, l.Seed)
	return b.String()
}
